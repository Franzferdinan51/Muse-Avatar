#pragma once

#include <stdbool.h>
#include <stdint.h>

#include "muse_pixel.h"   /* muse_pose_t, MUSE_PX_W/H - shared with Jollybot */

/*
 * Procedural pixel-art renderer for the Juno character - the second
 * avatar in this repo, designed 2026-10-14 as a sibling to Jollybot
 * (avatar/muse_pixel.c). Same 64x64 grid, same pose input, same
 * scale/alpha/bg-hook contract, so a caller can swap faces without
 * touching its frame loop.
 *
 * Juno is a black duck in a suit and sunglasses. The character is a
 * set of palette sprite maps (avatar/juno_sprites.h, generated by
 * tools/make_juno.py) stamped into the same kind of index+mask
 * framebuffer Jollybot uses: background cells stay transparent (the
 * character sits on the caller's backdrop), a soft black floor
 * shadow and a state-coloured aura sit underneath.
 */

/* Accent colour of a mode (for the surrounding UI), as 0xRRGGBB. */
uint32_t juno_pixel_accent(muse_mode_t mode);

/* Render one frame into Juno's own MUSE_PX_W x MUSE_PX_H grid. */
void juno_pixel_render(const muse_pose_t *pose);

/* Size (square, in screen pixels) juno_pixel_scale() blows the grid up to. */
void juno_pixel_set_size(int px);

/* Screen pixels [x0, x1] x [y0, y1] of the blown-up frame as RGB565. */
void juno_pixel_scale(uint16_t *dst, int stride_px, int x0, int x1, int y0, int y1);

/* Alpha companion for RGB565A8 targets (0 bg, partial aura/shadow, 255 body). */
void juno_pixel_scale_alpha(uint8_t *dst, int stride_px, int x0, int x1, int y0, int y1);

/* Backdrop hook, same contract as muse_pixel_set_bg_hook. */
void juno_pixel_set_bg_hook(uint16_t (*fn)(int grid_row));
