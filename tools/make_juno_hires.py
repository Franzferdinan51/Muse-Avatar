#!/usr/bin/env python3
"""Juno hi-res portrait - 128x128, profile, gradient-shaded.

An original Juno original at four times the sprite grid: same duck,
same suit and shades, but shaded with ramps instead of flat fills.
Generated by Juno for the Muse-Avatar collection.
"""
from PIL import Image
import numpy as np

S = 128
img = np.zeros((S, S, 4), dtype=np.float32)  # id buffer in alpha


def put(x, y, part, shade):
    if 0 <= x < S and 0 <= y < S:
        img[y, x] = (part, shade, 0, 255)


def ellipse(cx, cy, rx, ry, part, shade_fn):
    for y in range(S):
        for x in range(S):
            d = ((x - cx) / rx) ** 2 + ((y - cy) / ry) ** 2
            if d <= 1.0:
                put(x, y, part, shade_fn(x, y, d))


def ramp(stops):
    def f(v):
        v = max(0.0, min(1.0, v))
        for i in range(len(stops) - 1):
            if v <= stops[i + 1][0]:
                t = (v - stops[i][0]) / (stops[i + 1][0] - stops[i][0])
                a, b = stops[i][1], stops[i + 1][1]
                return tuple(a[k] + (b[k] - a[k]) * t for k in range(3))
        return stops[-1][1]
    return f


FUR = ramp([(0.0, (17, 18, 23)), (0.55, (26, 27, 34)), (1.0, (52, 53, 63))])
BILL = ramp([(0.0, (252, 199, 74)), (0.6, (247, 183, 49)), (1.0, (226, 124, 10))])
SUIT = ramp([(0.0, (44, 45, 54)), (1.0, (20, 21, 26))])

# shoulders / suit - starts high enough to tuck under the chin
for y in range(78, S):
    w = 36 + (y - 78) * 0.45
    for x in range(S):
        if abs(x - 64) <= w:
            v = (y - 78) / 50
            img[y, x] = (3, v, 0, 255)
# shirt + tie
for y in range(86, 120):
    t = (y - 86) / 34
    half = 11 * (1 - t) + 1.5
    for x in range(int(64 - half), int(64 + half) + 1):
        img[y, x] = (4, 0, 0, 255)
for y in range(86, 118):
    for x in range(62, 67):
        img[y, x] = (5, 0, 0, 255)
# head
ellipse(68, 50, 35, 32, 1, lambda x, y, d: 0)
for y in range(S):
    for x in range(S):
        if img[y, x, 0] == 1:
            d = ((x - 50) / 54) ** 2 + ((y - 24) / 46) ** 2
            img[y, x, 1] = max(0.0, 1.0 - d) ** 1.6
# tuft
for dx, hh in ((-7, 6), (0, 8), (7, 6)):
    for i in range(hh):
        for x in range(68 + dx - 2, 68 + dx + 3 - (1 if i > hh - 3 else 0)):
            put(x, 20 - i, 1, 0.75)
# bill (profile, pointing left): two stacked ellipses
ellipse(38, 60, 22, 7.5, 2, lambda x, y, d: 0)
for y in range(S):
    for x in range(S):
        if img[y, x, 0] == 2:
            img[y, x, 1] = ((y - 53) / 15)
ellipse(38, 69, 17, 4.2, 2, lambda x, y, d: 0)
for y in range(S):
    for x in range(S):
        if img[y, x, 0] == 2 and y >= 66:
            img[y, x, 1] = 0.85
# mouth seam + nostril
for x in range(20, 58):
    put(x, 66, 6, 0)
put(46, 57, 6, 0)
put(47, 57, 6, 0)
# sunglasses: near lens + far sliver + bridge + temple
for y in range(S):
    for x in range(S):
        near = ((x - 44) / 17) ** 2 + ((y - 42) / 10) ** 2 <= 1.0
        far = ((x - 82) / 8.5) ** 2 + ((y - 42) / 9) ** 2 <= 1.0
        bridge = 58 <= x <= 74 and 39 <= y <= 44
        temple = 88 <= x <= 96 and 39 <= y <= 43
        if near or far or bridge or temple:
            img[y, x] = (7, 0, 0, 255)
# glints: diagonal streak on the near lens, dot on the far
for i in range(7):
    put(36 + i, 36 + i, 8, 0)
    put(37 + i, 36 + i, 8, 0)
put(82, 38, 8, 0)
put(83, 38, 8, 0)

# outline: silhouette cells touching transparency
silh = img[:, :, 3] > 0
out = img.copy()
for y in range(S):
    for x in range(S):
        if not silh[y, x]:
            continue
        for nx, ny in ((x - 1, y), (x + 1, y), (x, y - 1), (x, y + 1)):
            if not (0 <= nx < S and 0 <= ny < S) or not silh[ny, nx]:
                out[y, x] = (9, 0, 0, 255)
                break
img = out

COLORS = {
    1: lambda s: FUR(s),
    2: lambda s: BILL(s),
    3: lambda s: SUIT(s),
    4: lambda s: (245, 242, 234),
    5: lambda s: (12, 12, 16),
    6: lambda s: (184, 95, 0),
    7: lambda s: (8, 8, 11),
    8: lambda s: (255, 255, 255),
    9: lambda s: (16, 13, 11),
}
rgba = np.zeros((S, S, 4), dtype=np.uint8)
for y in range(S):
    for x in range(S):
        p, s, _, a = img[y, x]
        if a > 0:
            rgba[y, x] = (*[int(v) for v in COLORS[int(p)](s)], 255)
Image.fromarray(rgba, "RGBA").save("/home/hatch/workspace/juno-design/juno_hires.png")
bg = Image.new("RGBA", (S * 4, S * 4), (10, 18, 38, 255))
bg.alpha_composite(Image.fromarray(rgba, "RGBA").resize((S * 4, S * 4), Image.NEAREST))
bg.convert("RGB").save("/home/hatch/workspace/juno-design/juno_hires_prev.jpg", quality=88)
print("hires juno written")
